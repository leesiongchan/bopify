panel.setFrame(NSRect(x: 100, y: 100, width: 410, height: 340), display: true)
panel.makeKeyAndOrderFront(nil)
let directory = FileManager.default.temporaryDirectory.appendingPathComponent("bopify-glass-gestures", isDirectory: true)
try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
@MainActor func capture(_ name: String) throws {
    guard let view = panel.contentView, let bitmap = view.bitmapImageRepForCachingDisplay(in: view.bounds) else { return }
    view.needsDisplay = true
    view.displayIfNeeded()
    view.cacheDisplay(in: view.bounds, to: bitmap)
    try bitmap.representation(using: .png, properties: [:])!.write(to: directory.appendingPathComponent(name + ".png"))
}
@MainActor func mouse(_ type: NSEvent.EventType, _ x: CGFloat, _ y: CGFloat) {
    let event = NSEvent.mouseEvent(with: type, location: NSPoint(x: x, y: 340-y), modifierFlags: [],
                                  timestamp: ProcessInfo.processInfo.systemUptime, windowNumber: panel.windowNumber,
                                  context: nil, eventNumber: 0, clickCount: 1, pressure: type == .leftMouseUp ? 0 : 1)!
    panel.sendEvent(event)
}
